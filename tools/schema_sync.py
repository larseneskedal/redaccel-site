#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Keep every page's JSON-LD in step with its visible content.

Usage: python3 tools/schema_sync.py [--check] [--date YYYY-MM-DD]

For each site/**/index.html:
  * FAQPage: if the page shows <details class="faq-item"> blocks and its JSON-LD has no
    FAQPage node, add one built from the visible questions and answers (Peec action
    "Mark up the existing FAQ with FAQPage schema", 2026-10-05).
  * Service nodes get a dateModified (Peec action "Add a last-updated date to your
    commercial schema"). The date is the page's "Updated <Month YYYY>" footer stamp
    unless --date is given, in which case pages touched in this run get that date.
  * BreadcrumbList: added from the visible breadcrumb trail when missing (Peec LOW).
  * Home page: the WebSite node carries a SearchAction for /search/ and a dateModified.
  * Pages with no JSON-LD at all get a WebPage node (Peec LOW, checklist page).

Idempotent. --check exits 1 if any page would change. Blog posts are regenerated by
publish_article.py and already carry everything, so they come out unchanged.
"""
import datetime
import io
import json
import os
import re
import sys
from html.parser import HTMLParser

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SITE_DIR = os.path.join(ROOT, "site")
sys.path.insert(0, HERE)
import _parts  # noqa: E402

SITE = _parts.SITE
JSONLD_RE = re.compile(r'<script type="application/ld\+json">\n?(.*?)\n?</script>', re.S)
TITLE_RE = re.compile(r"<title>(.*?)</title>", re.S)
DESC_RE = re.compile(r'<meta name="description" content="(.*?)">', re.S)
CANON_RE = re.compile(r'<link rel="canonical" href="(.*?)">')
UPDATED_RE = re.compile(r"<span>Updated ([A-Z][a-z]+) (\d{4})</span>")
MONTHS = ["January", "February", "March", "April", "May", "June", "July", "August",
          "September", "October", "November", "December"]


class _Text(HTMLParser):
    """Collect the text of the FAQ pairs and the breadcrumb trail."""

    def __init__(self):
        HTMLParser.__init__(self, convert_charrefs=True)
        self.faq = []          # [(question, answer)]
        self.crumbs = []       # [(label, href)]
        self._stack = []
        self._in_item = False
        self._q = None
        self._a = None
        self._in_summary = False
        self._in_answer = 0
        self._in_crumbs = False
        self._crumb_href = None
        self._crumb_text = None

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        cls = a.get("class", "")
        if tag == "details" and "faq-item" in cls:
            self._in_item = True
            self._q, self._a = [], []
        elif self._in_item and tag == "summary":
            self._in_summary = True
        elif self._in_item and tag == "div" and "faq-a" in cls:
            self._in_answer = 1
        elif self._in_answer and tag == "div":
            self._in_answer += 1
        elif tag == "nav" and "crumbs" in cls:
            self._in_crumbs = True
        elif self._in_crumbs and tag in ("a", "span") and a.get("aria-hidden") != "true":
            self._crumb_href = a.get("href")
            self._crumb_text = []

    def handle_endtag(self, tag):
        if tag == "summary" and self._in_summary:
            self._in_summary = False
        elif tag == "div" and self._in_answer:
            self._in_answer -= 1
        elif tag == "details" and self._in_item:
            q = " ".join("".join(self._q).split())
            ans = " ".join("".join(self._a).split())
            if q and ans:
                self.faq.append((q, ans))
            self._in_item = False
        elif tag == "nav" and self._in_crumbs:
            self._in_crumbs = False
        elif self._in_crumbs and tag in ("a", "span") and self._crumb_text is not None:
            label = " ".join("".join(self._crumb_text).split())
            if label:
                self.crumbs.append((label, self._crumb_href))
            self._crumb_text = None

    def handle_data(self, data):
        if self._in_summary:
            self._q.append(data)
        elif self._in_answer:
            self._a.append(data + " ")
        elif self._in_crumbs and self._crumb_text is not None:
            self._crumb_text.append(data)


def page_url(html, rel):
    m = CANON_RE.search(html)
    if m:
        return m.group(1)
    d = os.path.dirname(rel).replace(os.sep, "/")
    return SITE + "/" + (d + "/" if d else "")


def updated_date(html):
    m = UPDATED_RE.search(html)
    if not m or m.group(1) not in MONTHS:
        return None
    return "%s-%02d-01" % (m.group(2), MONTHS.index(m.group(1)) + 1)


def nodes_of(graph, t):
    return [n for n in graph if n.get("@type") == t]


def sync(html, rel, date):
    url = page_url(html, rel)
    is_home = rel == "index.html"
    m = JSONLD_RE.search(html)
    if m:
        doc = json.loads(m.group(1))
    else:
        doc = {"@context": "https://schema.org", "@graph": []}
    if "@graph" not in doc:
        doc = {"@context": "https://schema.org", "@graph": [doc]}
    graph = doc["@graph"]
    p = _Text()
    p.feed(html)

    changed = []
    # 1. FAQPage from the visible FAQ
    if p.faq and not nodes_of(graph, "FAQPage"):
        graph.append({"@type": "FAQPage", "mainEntity": [
            {"@type": "Question", "name": q,
             "acceptedAnswer": {"@type": "Answer", "text": a}} for q, a in p.faq]})
        changed.append("FAQPage")

    # 2. dateModified on commercial nodes
    stamp = date or updated_date(html)
    if stamp:
        for n in graph:
            if n.get("@type") in ("Service", "Offer", "Product") and _needs(n, stamp, date):
                n["dateModified"] = stamp
                changed.append("Service.dateModified")
            for o in n.get("offers", []) if isinstance(n.get("offers"), list) else []:
                if _needs(o, stamp, date):
                    o["dateModified"] = stamp
                    changed.append("Offer.dateModified")

    # 3. BreadcrumbList from the visible trail
    if not is_home and len(p.crumbs) >= 2 and not nodes_of(graph, "BreadcrumbList"):
        items = []
        for i, (label, href) in enumerate(p.crumbs, 1):
            name = "Home" if href == "/" else label
            item = url if href is None else (SITE + href if href.startswith("/") else href)
            items.append({"@type": "ListItem", "position": i, "name": name, "item": item})
        graph.append({"@type": "BreadcrumbList", "itemListElement": items})
        changed.append("BreadcrumbList")

    # 4. Home page WebSite node: search action and date
    if is_home:
        for n in nodes_of(graph, "WebSite"):
            want = {"@type": "SearchAction",
                    "target": {"@type": "EntryPoint",
                               "urlTemplate": SITE + "/search/?q={search_term_string}"},
                    "query-input": "required name=search_term_string"}
            if n.get("potentialAction") != want:
                n["potentialAction"] = want
                changed.append("SearchAction")
            if stamp and _needs(n, stamp, date):
                n["dateModified"] = stamp
                changed.append("WebSite.dateModified")

    # 5. Pages with nothing describing them
    if not m and not nodes_of(graph, "WebPage"):
        tm = TITLE_RE.search(html)
        dm = DESC_RE.search(html)
        node = {"@type": "WebPage", "@id": url, "url": url,
                "name": _unesc(tm.group(1)) if tm else "",
                "isPartOf": {"@id": SITE + "/#website"},
                "publisher": {"@id": SITE + "/#org"}}
        if dm:
            node["description"] = _unesc(dm.group(1))
        if stamp:
            node["dateModified"] = stamp
        graph.insert(0, node)
        changed.append("WebPage")

    if not changed:
        return html, []
    block = '<script type="application/ld+json">\n%s\n</script>' % json.dumps(doc, indent=2, ensure_ascii=False)
    if m:
        out = html[:m.start()] + block + html[m.end():]
    else:
        out = html.replace("</head>", block + "\n</head>", 1)
    return out, sorted(set(changed))


def _needs(node, stamp, explicit):
    """With --date, every dated node moves to it; without, only undated nodes get a date."""
    return node.get("dateModified") != stamp if explicit else not node.get("dateModified")


def _unesc(s):
    return (s.replace("&amp;", "&").replace("&lt;", "<").replace("&gt;", ">")
             .replace("&quot;", '"').replace("&#39;", "'"))


def main(argv):
    check = "--check" in argv
    date = None
    if "--date" in argv:
        date = argv[argv.index("--date") + 1]
        datetime.date.fromisoformat(date)
    touched = []
    for dirpath, _dirs, files in os.walk(SITE_DIR):
        if os.sep + "functions" in dirpath:
            continue
        for name in files:
            if name != "index.html":
                continue
            path = os.path.join(dirpath, name)
            rel = os.path.relpath(path, SITE_DIR)
            with io.open(path, encoding="utf-8") as fh:
                html = fh.read()
            new, changed = sync(html, rel, date)
            if changed:
                touched.append((rel, changed))
                if not check:
                    with io.open(path, "w", encoding="utf-8") as fh:
                        fh.write(new)
    for rel, changed in sorted(touched):
        print(("would update " if check else "updated ") + rel + ": " + ", ".join(changed))
    return 1 if (check and touched) else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
